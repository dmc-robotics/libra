import Foundation
@testable import LibraKit
import Testing
import simd

@Suite struct ExportTests {
    /// A 1 kg 0.1 m cube centered at (1, 0, 0) and an unassigned part, in one body whose frame sits at (1, 0, 0)
    /// turned a quarter about Z.
    static var document: LibraDocument {
        let cube = Fixtures.boxPart(name: "Cube", size: [0.1, 0.1, 0.1], corner: [0.95, -0.05, -0.05], mass: .measured(1))
        let loose = Fixtures.boxPart(name: "Loose", size: [0.1, 0.1, 0.1], corner: [2, 0, 0])
        let frame = Frame.file.moved(to: [1, 0, 0]).rotatedQuarterTurn(about: .z)
        return LibraDocument(
            parts: [cube, loose],
            bodies: [Body(name: "Arm Link", partIDs: [cube.id, loose.id], frame: frame)]
        )
    }

    static var report: MassReport { MassReport(document: document, modelName: "Test Robot") }

    @Test func reportExpressesBodyInItsFrame() throws {
        let body = try #require(Self.report.bodies.first)
        expectClose(body.position, [1, 0, 0])
        expectClose(body.summary.properties.centerOfMass, [0, 0, 0], tolerance: 1e-12)
        expectClose(body.summary.properties.mass, 1)
        #expect(body.summary.unassignedCount == 1)
    }

    @Test func mjcf() {
        let inertia = 1.0 * (0.01 + 0.01) / 12
        let expected = """
        <!-- Generated by Libra. SI units (m, kg, kg·m²). Body poses are relative to the Libra frame;
             each inertial is in its body's frame. Add joints and nest bodies to build the kinematic tree. -->
        <mujoco model="Test Robot">
          <worldbody>
            <body name="Arm_Link" pos="1 0 0" quat="0.707106781 0 0 0.707106781">
              <inertial pos="0 0 0" mass="1" fullinertia="\(ExportFormat.number(inertia)) \(ExportFormat.number(inertia)) \(ExportFormat.number(inertia)) 0 0 0"/>
              <!-- 1 of 2 parts have no mass and are left out -->
            </body>
          </worldbody>
        </mujoco>

        """
        #expect(ExportKind.mjcf.text(for: Self.report) == expected)
    }

    @Test func urdf() {
        let text = ExportKind.urdf.text(for: Self.report)
        #expect(text.contains("<robot name=\"Test_Robot\">"))
        #expect(text.contains("<link name=\"Arm_Link\">"))
        #expect(text.contains("rpy=\"0 0 1.57079633\""))
        #expect(text.contains("<mass value=\"1\"/>"))
        #expect(text.contains("<origin xyz=\"0 0 0\" rpy=\"0 0 0\"/>"))
    }

    @Test func csvHasRowPerAssemblyBodyAndPart() {
        let lines = ExportKind.csv.text(for: Self.report).split(separator: "\n")
        #expect(lines.count == 1 + 1 + 1 + 2)
        #expect(lines[0] == Substring(CSVExporter.header))
        #expect(lines[2].hasPrefix("body,Arm Link,body,1,"))
        // The unassigned part has empty values and counts as unassigned
        #expect(lines[4] == "part,Loose,libra,,,,,,,,,,,1")
    }

    @Test func jsonParses() throws {
        let data = Data(ExportKind.json.text(for: Self.report).utf8)
        let object = try #require(try JSONSerialization.jsonObject(with: data) as? [String: Any])
        let bodies = try #require(object["bodies"] as? [[String: Any]])
        #expect(bodies.first?["name"] as? String == "Arm Link")
        #expect((object["parts"] as? [Any])?.count == 2)
    }

    @Test func noBodiesExportsWholeAssembly() {
        var document = Self.document
        document.bodies = []
        let report = MassReport(document: document, modelName: "Robot")
        #expect(report.bodies.count == 1)
        #expect(report.bodies[0].name == "Robot")
        #expect(report.bodies[0].partNames.count == 2)
    }

    @Test func rollPitchYawRoundTrips() {
        let rotation = simd_double3x3(simd_quatd(angle: 0.3, axis: [0, 0, 1]) * simd_quatd(angle: -0.4, axis: [0, 1, 0]) * simd_quatd(angle: 0.5, axis: [1, 0, 0]))
        let angles = ExportFormat.rollPitchYaw(rotation)
        expectClose(angles[0], 0.5)
        expectClose(angles[1], -0.4)
        expectClose(angles[2], 0.3)
    }

    @Test func identifiersAreSafeAndUnique() {
        #expect(ExportFormat.identifiers(for: ["Hub v3:1", "Hub v3:1", ""]) == ["Hub_v3_1", "Hub_v3_1_2", "body"])
    }
}

@Suite struct DocumentTests {
    @Test func roundTripsThroughJSON() throws {
        var document = ExportTests.document
        document.parts[0].mass = .override(MassOverride(
            mass: 0.2, centerOfMass: [0, 0, 0.01], inertia: InertiaTensor(xx: 1, yy: 2, zz: 3, xy: 0.1, xz: 0.2, yz: 0.3),
            frame: Frame.file.rotatedQuarterTurn(about: .x)
        ))
        document.libraFrame = Frame.file.moved(to: [0.1, 0.2, 0.3])
        let decoded = try LibraDocument.decoded(from: document.encoded())
        #expect(decoded == document)
    }

    @Test func rejectsNewerFormat() throws {
        var document = LibraDocument()
        document.formatVersion = LibraDocument.currentFormatVersion + 1
        let data = try document.encoded()
        #expect(throws: LibraDocument.FormatError.self) {
            try LibraDocument.decoded(from: data)
        }
    }
}
